/* The app's words in each language. English is the default; a language is picked from the browser's
   until the person chooses one (Settings in the app, the header on the site). The choice is kept under
   "oc-lang", the key the site and its docs use too, so a language picked on one is the language of the
   others. A new language is one more dictionary of the same shape: TypeScript lists any missing entry. */
import type { ReactNode } from "react";

export type Lang = "en" | "tr";
export const LANGS: Record<Lang, string> = { en: "English", tr: "Türkçe" };
const KEY = "oc-lang";

const known = (l: string | null | undefined): Lang | null => (l && l in LANGS ? (l as Lang) : null);
const stored = () => { try { return known(localStorage.getItem(KEY)); } catch { return null; } };
const fromBrowser = (): Lang => {
  for (const l of navigator.languages ?? [navigator.language]) { const k = known(l?.slice(0, 2).toLowerCase()); if (k) return k; }
  return "en";
};

export const lang: Lang = stored() ?? fromBrowser();
/** For dates, numbers and case-insensitive search (Turkish has its own i/İ). */
export const LOCALE = { en: "en", tr: "tr-TR" }[lang];
document.documentElement.lang = lang;

/** Keeps the choice and reloads, so every screen reads the new language from the start. */
export function setLang(l: Lang) {
  try { localStorage.setItem(KEY, l); } catch { /* private mode: this page only */ }
  location.reload();
}

